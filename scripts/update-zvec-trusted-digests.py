#!/usr/bin/env python3
"""Resolve Quay multi-architecture zvec digests into a reviewable env file."""
from __future__ import annotations

import argparse
import json
import os
import pathlib
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from typing import Any

ACCEPT_INDEX = ", ".join(
    (
        "application/vnd.oci.image.index.v1+json",
        "application/vnd.docker.distribution.manifest.list.v2+json",
        "application/vnd.oci.image.manifest.v1+json",
        "application/vnd.docker.distribution.manifest.v2+json",
    )
)
ACCEPT_MANIFEST = ", ".join(
    (
        "application/vnd.oci.image.manifest.v1+json",
        "application/vnd.docker.distribution.manifest.v2+json",
    )
)


def _request(url: str, *, accept: str, token: str | None = None) -> tuple[dict[str, Any], dict[str, str]]:
    headers = {"Accept": accept, "User-Agent": "engram-zvec-digest-refresh/1"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as response:
            return json.load(response), dict(response.headers.items())
    except urllib.error.HTTPError as error:
        if error.code != 401:
            raise
        challenge = error.headers.get("WWW-Authenticate", "")
        values = dict(
            part.strip().split("=", 1)
            for part in challenge.removeprefix("Bearer ").split(",")
            if "=" in part
        )
        realm = values.get("realm", "").strip('"')
        service = values.get("service", "").strip('"')
        scope = values.get("scope", "").strip('"')
        if not realm:
            raise
        query = urllib.parse.urlencode({key: value for key, value in {"service": service, "scope": scope}.items() if value})
        with urllib.request.urlopen(f"{realm}?{query}", timeout=30) as token_response:
            token_document = json.load(token_response)
        return _request(url, accept=accept, token=token_document["token"])


def _registry_parts(image: str) -> tuple[str, str]:
    image = image.removeprefix("https://").removeprefix("http://")
    if "/" not in image:
        raise ValueError(f"image must include a registry and repository: {image}")
    return image.split("/", 1)


def _resolve_image(image: str, tag: str) -> dict[str, Any]:
    registry, repository = _registry_parts(image)
    base = f"https://{registry}/v2/{repository}"
    manifest, headers = _request(f"{base}/manifests/{tag}", accept=ACCEPT_INDEX)
    entries = manifest.get("manifests")
    if not isinstance(entries, list):
        raise ValueError(f"{image}:{tag} is not a multi-architecture manifest index")

    platforms: dict[str, str] = {}
    revisions: dict[str, str] = {}
    for entry in entries:
        platform = entry.get("platform", {})
        architecture = platform.get("architecture")
        digest = entry.get("digest")
        if platform.get("os") != "linux" or architecture not in {"amd64", "arm64"} or not isinstance(digest, str):
            continue
        platform_key = f"linux/{architecture}"
        platforms[platform_key] = digest
        platform_manifest, _ = _request(f"{base}/manifests/{digest}", accept=ACCEPT_MANIFEST)
        config_digest = platform_manifest.get("config", {}).get("digest")
        if isinstance(config_digest, str):
            config, _ = _request(f"{base}/blobs/{config_digest}", accept="application/json")
            revision = config.get("config", {}).get("Labels", {}).get("org.opencontainers.image.revision")
            if isinstance(revision, str) and revision:
                revisions[platform_key] = revision

    if set(platforms) != {"linux/amd64", "linux/arm64"}:
        raise ValueError(f"{image}:{tag} did not expose both Linux platforms: {sorted(platforms)}")
    return {
        "image": image,
        "tag": tag,
        "index_digest": headers.get("Docker-Content-Digest"),
        "platform_digests": platforms,
        "platform_revisions": revisions,
    }


def write_env(output: pathlib.Path, zvec: dict[str, Any], proxy: dict[str, Any]) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by scripts/update-zvec-trusted-digests.py; review the PR before deployment.",
        f"# Refreshed at {datetime.now(timezone.utc).isoformat()}",
        f"# zvec index digest: {zvec.get('index_digest') or 'unknown'}",
        f"# proxy index digest: {proxy.get('index_digest') or 'unknown'}",
        f"ZVEC_GREP_IMAGE_DIGEST_LINUX_AMD64={zvec['platform_digests']['linux/amd64']}",
        f"ZVEC_GREP_IMAGE_DIGEST_LINUX_ARM64={zvec['platform_digests']['linux/arm64']}",
        f"ZVEC_GREP_PROXY_IMAGE_DIGEST_LINUX_AMD64={proxy['platform_digests']['linux/amd64']}",
        f"ZVEC_GREP_PROXY_IMAGE_DIGEST_LINUX_ARM64={proxy['platform_digests']['linux/arm64']}",
    ]
    temporary = output.with_suffix(f"{output.suffix}.{os.getpid()}.tmp")
    temporary.write_text("\n".join(lines) + "\n")
    temporary.chmod(0o600)
    temporary.replace(output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tag", default="latest")
    parser.add_argument("--zvec-image", default="quay.io/jordigilh/zvec-grep")
    parser.add_argument("--proxy-image", default="quay.io/jordigilh/zg-loopback-proxy")
    parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path("deploy/zvec-grep/trusted-digests.env"))
    args = parser.parse_args()
    write_env(args.output, _resolve_image(args.zvec_image, args.tag), _resolve_image(args.proxy_image, args.tag))


if __name__ == "__main__":
    main()
